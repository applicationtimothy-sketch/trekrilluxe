const fs = require('fs');
const path = require('path');
const postgres = require('postgres');

require('dotenv').config({ path: path.join(__dirname, '.env') });

const connectionString = process.env.DATABASE_URL;
if (!connectionString) {
  throw new Error('DATABASE_URL is required. Set it in backend/.env or the hosting environment.');
}

const sql = postgres(connectionString);
const SITE_CONTENT_SEED_FILE = path.join(__dirname, 'data', 'site-content.json');

async function initializeDatabase() {
  const siteContentDefaults = JSON.parse(fs.readFileSync(SITE_CONTENT_SEED_FILE, 'utf8'));

  await sql.begin(async (tx) => {
    await tx`
      CREATE TABLE IF NOT EXISTS tours (
        id INTEGER PRIMARY KEY,
        data JSONB NOT NULL
      )
    `;
    await tx`CREATE SEQUENCE IF NOT EXISTS tours_id_seq`;
    await tx`ALTER TABLE tours ALTER COLUMN id SET DEFAULT nextval('tours_id_seq')`;
    await tx`
      SELECT setval(
        'tours_id_seq',
        GREATEST((SELECT COALESCE(MAX(id), 0) + 1 FROM tours), 1),
        false
      )
    `;
    await tx`
      UPDATE tours
      SET data = (data #>> '{}')::jsonb
      WHERE jsonb_typeof(data) = 'string'
    `;
    await tx`
      CREATE TABLE IF NOT EXISTS bookings (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        email TEXT NOT NULL,
        phone TEXT NOT NULL,
        tour_id INTEGER NOT NULL,
        tour_title TEXT NOT NULL,
        travel_date TEXT NOT NULL,
        people INTEGER NOT NULL,
        notes TEXT NOT NULL DEFAULT '',
        status TEXT NOT NULL DEFAULT 'pending',
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `;
    await tx`
      CREATE TABLE IF NOT EXISTS mpesa_payments (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
        merchant_request_id TEXT,
        checkout_request_id TEXT UNIQUE,
        phone TEXT NOT NULL,
        amount INTEGER NOT NULL CHECK (amount > 0),
        mpesa_receipt_number TEXT,
        status TEXT NOT NULL DEFAULT 'initiating' CHECK (status IN ('initiating', 'pending', 'success', 'failed')),
        result_code TEXT,
        result_description TEXT NOT NULL DEFAULT '',
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `;
    await tx`CREATE INDEX IF NOT EXISTS mpesa_payments_booking_created_at_idx ON mpesa_payments (booking_id, created_at DESC)`;
    await tx`
      CREATE TABLE IF NOT EXISTS tour_reviews (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        tour_id INTEGER NOT NULL REFERENCES tours(id) ON DELETE CASCADE,
        reviewer_name TEXT NOT NULL,
        rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
        review TEXT NOT NULL DEFAULT '',
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `;
    await tx`CREATE INDEX IF NOT EXISTS tour_reviews_tour_created_at_idx ON tour_reviews (tour_id, created_at DESC)`;
    await tx`
      CREATE TABLE IF NOT EXISTS messages (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        email TEXT NOT NULL,
        phone TEXT NOT NULL DEFAULT '',
        subject TEXT NOT NULL,
        message TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `;
    await tx`
      CREATE TABLE IF NOT EXISTS subscribers (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        email TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `;
    await tx`
      CREATE UNIQUE INDEX IF NOT EXISTS subscribers_email_lower_idx
      ON subscribers (LOWER(email))
    `;
    await tx`
      CREATE TABLE IF NOT EXISTS page_views (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        path TEXT NOT NULL,
        viewed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `;
    await tx`CREATE INDEX IF NOT EXISTS page_views_viewed_at_idx ON page_views (viewed_at)`;
    await tx`
      CREATE TABLE IF NOT EXISTS site_content (
        section TEXT NOT NULL,
        id TEXT NOT NULL,
        sort_order INTEGER NOT NULL DEFAULT 0,
        data JSONB NOT NULL,
        PRIMARY KEY (section, id)
      )
    `;
    await tx`CREATE INDEX IF NOT EXISTS site_content_section_order_idx ON site_content (section, sort_order, id)`;
    await tx`
      CREATE TABLE IF NOT EXISTS site_settings (
        id INTEGER PRIMARY KEY CHECK (id = 1),
        data JSONB NOT NULL
      )
    `;
    await tx`
      CREATE TABLE IF NOT EXISTS site_content_migrations (
        name TEXT PRIMARY KEY,
        applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `;

    const [seedMigration] = await tx`
      INSERT INTO site_content_migrations (name)
      VALUES ('initial-site-content')
      ON CONFLICT (name) DO NOTHING
      RETURNING name
    `;
    if (seedMigration) {
      for (const section of ['testimonials']) {
        for (const item of siteContentDefaults[section]) {
          await tx`
            INSERT INTO site_content (section, id, sort_order, data)
            VALUES (${section}, ${item.id}, ${item.sortOrder}, ${tx.json(item)})
            ON CONFLICT (section, id) DO NOTHING
          `;
        }
      }
      await tx`
        INSERT INTO site_settings (id, data)
        VALUES (1, ${tx.json(siteContentDefaults.settings)})
        ON CONFLICT (id) DO NOTHING
      `;
    }

    const [contactDetailsMigration] = await tx`
      INSERT INTO site_content_migrations (name)
      VALUES ('trekrilluxe-contact-details')
      ON CONFLICT (name) DO NOTHING
      RETURNING name
    `;
    if (contactDetailsMigration) {
      await tx`
        UPDATE site_settings
        SET data = jsonb_set(
          jsonb_set(
            jsonb_set(
              jsonb_set(data, '{phone}', ${tx.json('+254 790 885540')}::jsonb, true),
              '{bookingPhone}', ${tx.json('+254 790 885540')}::jsonb, true
            ),
            '{email}', ${tx.json('trekrilluxesafaris@proton.me')}::jsonb, true
          ),
          '{bookingEmail}', ${tx.json('trekrilluxesafaris@proton.me')}::jsonb, true
        )
        WHERE id = 1
      `;
    }

    const [contactEmailMigration] = await tx`
      INSERT INTO site_content_migrations (name)
      VALUES ('trekrilluxe-correct-contact-email')
      ON CONFLICT (name) DO NOTHING
      RETURNING name
    `;
    if (contactEmailMigration) {
      await tx`
        UPDATE site_settings
        SET data = jsonb_set(data, '{email}', ${tx.json('trekrilluxesafaris@proton.me')}::jsonb, true)
        WHERE id = 1 AND data->>'email' = 'trekrilluxetoursafaris@proton.me'
      `;
      await tx`
        UPDATE site_settings
        SET data = jsonb_set(data, '{bookingEmail}', ${tx.json('trekrilluxesafaris@proton.me')}::jsonb, true)
        WHERE id = 1 AND data->>'bookingEmail' = 'trekrilluxetoursafaris@proton.me'
      `;
    }

    for (const table of ['bookings', 'messages', 'subscribers']) {
      await tx.unsafe(
        `SELECT setval(pg_get_serial_sequence('${table}', 'id'), COALESCE(MAX(id), 0) + 1, false) FROM ${table}`
      );
    }
  });
}

module.exports = { sql, initializeDatabase };
